#!/usr/bin/env python3
"""Generate the colour themes (assets/themes/theme-<name>.yaml and theme-<name>-invert.yaml) from the
four five-tone palettes: black, A, B, C, white.

Roles (normal):  background C (the 3/4 tone), text black, rules and hints B, selection plate white
with black text. "Invert" reverses the tones (black <-> white, A <-> C), so the screen goes dark.
See tools/palette-playground.html to try palettes.

usage: gen_themes.py
"""
import os

PALETTES = {
    # file name: (title, [black, A, B, C, white])
    "black": ("Amber", ["#110700", "#482008", "#975012", "#E58E2D", "#FFE0A0"]),
    "paper": ("Paper", ["#062027", "#17617D", "#399FC2", "#7AD2FD", "#D7F6FF"]),  # light blue (the old amber Paper hue-rotated)
    "mobile": ("Mobile", ["#0C1511", "#2A4B3D", "#7E955B", "#B1C594", "#EBEEC0"]),
    # phosphor green: Invert gives the classic green-on-black terminal look
    "terminal": ("Terminal", ["#010A02", "#0B3D1A", "#1FA043", "#59F07F", "#D3FFDF"]),
    # Grey panels (HARBOUR_PANEL=gray or an 8-bit grey driver): five greys. Not offered on colour screens.
    "gray": ("Gray", ["#000000", "#404040", "#808080", "#C0C0C0", "#FFFFFF"]),
    # Black-and-white panels (Sharp memory LCDs): the panel shows black, white and an ordered dither
    # for the tones between (platform::display::tone). Text and rules are solid black, the paper
    # solid white; plates and the desk are light dithers. Not offered on colour screens.
    "mono": ("1-bit", ["#000000", "#000000", "#9A9A9A", "#E4E4E4", "#FFFFFF"]),
}

# Roles that differ from the five-tone rules: on a 1-bit panel text in a mid tone would break up in
# the dither, so every text and rule role is the ink; the selection is inverted (black plate).
MONO_ROLES = {
    "secondary": "black",
    "muted": "black",
    "line": "black",
    "text_faint": "black",
    "widget_outline_dim": "black",
    "titlebar_stripe_a": "black",
    "select_bg": "black",
    "select_fg": "white",
    "tile_sel_bg": "mid",
}


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def hexc(c):
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(v))) for v in c)


def mix(a, b, t):
    ra, rb = rgb(a), rgb(b)
    return hexc([x + (y - x) * t for x, y in zip(ra, rb)])


def theme(name, title, tones, invert):
    t = tones[::-1] if invert else tones
    black, a, b, c, white = t
    bg, ink, muted = c, black, b
    sel_bg, sel_fg = white, black
    # The icons' "white": the brightest tone on a light screen, a lifted background on a dark one.
    icon_white = mix(bg, muted, 0.5) if invert else white
    n = name + ("-invert" if invert else "")
    lines = [
        f"# Generated by tools/gen_themes.py: {title}{' (inverted)' if invert else ''}. Do not edit by hand.",
        f"name: {n}",
        "colors:",
        "  palette:",
        *[f'    - "{x}"' for x in t],
        f'  background: "{bg}"',
        f'  foreground: "{ink}"',
        f'  primary: "{ink}"',
        f'  secondary: "{muted}"',
        f'  accent: "{ink}"',
        f'  muted: "{muted}"',
        f'  highlight: "{ink}"',
        f'  shadow: "{mix(bg, muted, 0.3)}"',
        f'  topbar_bg: "{bg}"',
        f'  widget_face: "{bg}"',
        f'  widget_face_active: "{bg}"',
        f'  widget_outline: "{ink}"',
        f'  widget_outline_dim: "{muted}"',
        f'  widget_highlight: "{white}"',
        f'  widget_shadow: "{black}"',
        f'  titlebar_stripe_a: "{muted}"',
        f'  titlebar_stripe_b: "{bg}"',
        f'  home_bg: "{bg}"',
        f'  home_bg_alt: "{bg}"',
        f'  surface_alt: "{mix(bg, muted, 0.2)}"',
        f'  surface_sunken: "{bg}"',
        f'  line: "{muted}"',
        f'  text_faint: "{muted}"',
        f'  accent_soft: "{mix(bg, muted, 0.4)}"',
        f'  select_bg: "{sel_bg}"   # highlights only',
        f'  select_fg: "{sel_fg}"',
        f'  icon_white: "{icon_white}"   # the white of icons',
        f'  tile_sel_bg: "{muted}"   # Home: the selected tile is only a mid-tone plate; icon and name keep their colours',
        f'  tile_sel_fg: "{ink}"',
    ]
    if name == "mono":
        tone = {"black": black, "white": white, "mid": b}
        for i, l in enumerate(lines):
            key = l.strip().split(":")[0]
            if key in MONO_ROLES:
                lines[i] = f'  {key}: "{tone[MONO_ROLES[key]]}"'
    return n, "\n".join(lines) + "\n"


root = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "themes")
for name, (title, tones) in PALETTES.items():
    for invert in (False, True):
        n, text = theme(name, title, tones, invert)
        with open(os.path.join(root, f"theme-{n}.yaml"), "w") as f:
            f.write(text)
        print("wrote", f"theme-{n}.yaml")
